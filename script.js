/* =========================================================
   KEYBOARD SHORTCUT PROTECTION
========================================================= */

typingInput.addEventListener(
    "keydown",
    function (event) {

        /*
           Prevent Ctrl/Cmd + V
        */

        if (
            (
                event.ctrlKey ||
                event.metaKey
            ) &&
            event.key.toLowerCase() === "v"
        ) {

            event.preventDefault();

        }


        /*
           Prevent Ctrl/Cmd + C
        */

        if (
            (
                event.ctrlKey ||
                event.metaKey
            ) &&
            event.key.toLowerCase() === "c"
        ) {

            event.preventDefault();

        }


        /*
           Prevent Ctrl/Cmd + X
        */

        if (
            (
                event.ctrlKey ||
                event.metaKey
            ) &&
            event.key.toLowerCase() === "x"
        ) {

            event.preventDefault();

        }

    }
);


